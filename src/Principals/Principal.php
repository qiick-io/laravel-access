<?php

declare(strict_types=1);

namespace Qiick\Access\Principals;

use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Carbon;
use Qiick\Access\Laravel\MigrationSettings;

/**
 * An actor that can own API keys and appear in the audit log: a member of an
 * organisation, a service or agent account, or an instance-level account
 * (design §15). Ids are UUID v7. Products extend it for their relations
 * (API keys, grants) and point access.principals.model at the subclass.
 *
 * organisation_key and instance_type are generated by the database; they are
 * never written from PHP.
 *
 * @property string $id
 * @property string $type
 * @property int|null $user_id
 * @property string|null $organisation_id
 * @property string|null $owner_principal_id
 * @property string $name
 * @property int|null $created_by
 * @property Carbon|null $expires_at
 * @property Carbon|null $deactivated_at
 * @property DeactivationReason|null $deactivation_reason
 * @property array<string, mixed>|null $metadata
 *
 * @api
 */
class Principal extends Model
{
    use HasUuids;

    protected $table = 'principals';

    /**
     * The attributes PrincipalDirectory creates rows with. Lifecycle fields
     * (deactivation, expiry) are written explicitly, never mass-assigned.
     *
     * @return list<string>
     */
    public function getFillable(): array
    {
        return ['type', 'user_id', 'organisation_id', 'owner_principal_id', 'name', 'created_by', 'metadata'];
    }

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'expires_at' => 'datetime',
            'deactivated_at' => 'datetime',
            'deactivation_reason' => DeactivationReason::class,
            'metadata' => 'array',
        ];
    }

    /**
     * @return BelongsTo<Model, $this>
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(MigrationSettings::userModel(), 'user_id');
    }

    /**
     * @return BelongsTo<static, $this>
     */
    public function owner(): BelongsTo
    {
        return $this->belongsTo(static::class, 'owner_principal_id');
    }

    /**
     * @return HasMany<static, $this>
     */
    public function owned(): HasMany
    {
        return $this->hasMany(static::class, 'owner_principal_id');
    }

    /**
     * Not deactivated and not expired. Owners are not checked here: use
     * PrincipalDirectory::isActive() for a use-time decision.
     *
     * @param  Builder<self>  $query
     */
    public function scopeActive(Builder $query): void
    {
        $query->whereNull('deactivated_at')
            ->where(static function (Builder $notExpired): void {
                $notExpired->whereNull('expires_at')->orWhere('expires_at', '>', now());
            });
    }

    /**
     * @param  Builder<self>  $query
     * @param  string|null  $organisationId  null: instance-level principals
     */
    public function scopeForOrganisation(Builder $query, ?string $organisationId): void
    {
        $query->where('organisation_id', $organisationId);
    }

    public function isInstanceLevel(): bool
    {
        return $this->organisation_id === null;
    }
}
